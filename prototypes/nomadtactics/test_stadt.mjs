import { chromium } from 'playwright';
import { createServer } from 'http';
import { readFileSync } from 'fs';
const srv = createServer((q, a) => { a.writeHead(200, { 'Content-Type': 'text/html' }); a.end(readFileSync('nomadtactics_stress_test.html')); }).listen(8815);
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const s = await b.newPage({ viewport: { width: 1280, height: 760 } });
s.on('pageerror', e => console.log('ERROR:', e.message, e.stack?.split('\n')[1]));
s.on('console', m => { if (m.type() === 'error') console.log('terminal:', m.text().slice(0, 300)); });
s.setDefaultTimeout(240000);
const t0 = Date.now();
await s.goto('http://localhost:8815/');
await s.waitForFunction(() => window.stressTest, null, { timeout: 240000 });
console.log('loaded', Date.now() - t0, 'ms');
await s.evaluate(() => { stressTest.setQuality('middle'); stressTest.ctl.target.set(-52, 0, 0); stressTest.camera('game'); });
await s.waitForTimeout(3000); await s.screenshot({ path: 'st_0.png' });
await s.evaluate(() => { stressTest.boom(-55, -24, 'rakete'); stressTest.boom(-46, 3, 'rakete'); });
await s.waitForTimeout(1500); await s.screenshot({ path: 'st_1.png' });
await s.evaluate(() => { stressTest.boom(-60, -21, 'rakete'); stressTest.boom(-63, -21, 'rakete'); stressTest.boom(-66, -22, 'rakete'); });
await s.waitForTimeout(2500); await s.screenshot({ path: 'st_2.png' });
console.log('before', JSON.stringify(await s.evaluate(() => stressTest.building.map(g => [g.kind, g.start - g.W.size, !!g.sinks, g.dead]))));
await s.evaluate(() => { stressTest.boom(-56, 14, 'super'); stressTest.fastForward(3.3); });
await s.waitForTimeout(1500); await s.screenshot({ path: 'st_3.png' });
await s.evaluate(() => stressTest.fastForward(1.5));
await s.waitForTimeout(1500); await s.screenshot({ path: 'st_4.png' });
await s.evaluate(() => stressTest.fastForward(4));
await s.waitForTimeout(1500); await s.screenshot({ path: 'st_5.png' });
console.log(JSON.stringify(await s.evaluate(() => stressTest.building.map(g => [g.kind, g.start - g.W.size, !!g.sinks, g.dead]))));
await b.close(); srv.close();
