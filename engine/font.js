function glyph(c) {
  const u = c.toUpperCase();
  return G[u] || G[c] || G['?'];
}

export function textWidth(t, opt = {}) {
  const s = opt.size || 1;
  return t.length ? (t.length * 4 - 1) * s : 0;
}

export function drawText(image, t, x, y, color, opt = {}) {
  const s = opt.size || 1;
  const [r, g, b, a] = Array.isArray(color) ? color : hex(color);
  const shadow = opt.shadow === false ? null : (opt.shadow || [14, 7, 27, 255]);
  const male = (ox, oy, rr, gg, bb, aa) => {
    let cx = x;
    for (const c of String(t)) {
      const m = glyph(c);
      for (let i = 0; i < 15; i++) if (m[i] === '1') {
        const px = cx + (i % 3) * s + ox, py = y + Math.floor(i / 3) * s + oy;
        for (let yy = 0; yy < s; yy++) for (let xx = 0; xx < s; xx++) image.mix(px + xx, py + yy, rr, gg, bb, aa);
      }
      cx += 4 * s;
    }
  };
  if (shadow) male(s, s, ...shadow);
  male(0, 0, r, g, b, a);
}

function hex(h) {
  const v = h.replace('#', '');
  return [parseInt(v.slice(0, 2), 16), parseInt(v.slice(2, 4), 16), parseInt(v.slice(4, 6), 16), 255];
}
